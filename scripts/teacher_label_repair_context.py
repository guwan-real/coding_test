#!/usr/bin/env python3
from __future__ import annotations

import argparse
import concurrent.futures
import json
import os
import re
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

from repair_context_utils import read_jsonl, render_numbered_code


SYSTEM_PROMPT = """You are a code repair context labeling assistant.

You will receive:
1. A bug report or repair query.
2. A source file.
3. Seed CORE lines derived from a gold patch or an existing pruner label.
4. Candidate regions generated by static analysis.

Your task:
Classify each candidate region as one of:
- CORE: directly involved in the fix, failure, or patch.
- SUPPORT: needed to understand or safely edit CORE, such as imports, enclosing scope, constants, helper definitions, class context, or control-flow boundaries.
- DROP: not needed for a patch-ready context.

Rules:
- Only classify the provided candidate regions.
- Do not invent line numbers.
- Do not invent symbols.
- Never remove seed CORE lines.
- Prefer concise SUPPORT.
- If a region is only broadly related but not needed for editing or understanding CORE, label it DROP.
- Output valid JSON only.

Output schema:
{
  "regions": [
    {
      "id": "R1",
      "label": "CORE | SUPPORT | DROP",
      "keep_lines": [1, 2, 3],
      "reason": "short reason",
      "confidence": 0.0
    }
  ],
  "overall_confidence": 0.0
}
"""


def build_user_prompt(sample: dict[str, Any], max_code_lines: int) -> str:
    code = str(sample.get("code", ""))
    numbered = render_numbered_code(
        code,
        candidate_regions=sample.get("candidate_regions", []),
        max_code_lines=max_code_lines,
    )
    payload = {
        "sample_id": sample.get("sample_id"),
        "source": sample.get("source"),
        "file_path": sample.get("file_path"),
        "seed_core_lines": sample.get("seed_core_lines", []),
        "candidate_regions": sample.get("candidate_regions", []),
    }
    return (
        "Query:\n"
        f"{sample.get('query', '')}\n\n"
        "Seed and candidate metadata:\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}\n\n"
        "Code with line numbers:\n"
        f"{numbered}\n"
    )


def normalize_base_url(base_url: str) -> str:
    base_url = base_url.rstrip("/")
    if base_url.endswith("/chat/completions"):
        return base_url
    return f"{base_url}/chat/completions"


def call_chat_completion(
    *,
    base_url: str,
    model: str,
    api_key: str | None,
    messages: list[dict[str, str]],
    temperature: float,
    max_tokens: int,
    timeout: int,
) -> str:
    body = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "max_tokens": max_tokens,
        "stream": False,
    }
    data = json.dumps(body).encode("utf-8")
    headers = {"Content-Type": "application/json"}
    if api_key:
        headers["Authorization"] = f"Bearer {api_key}"
    request = urllib.request.Request(
        normalize_base_url(base_url),
        data=data,
        headers=headers,
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=timeout) as response:
        payload = json.loads(response.read().decode("utf-8"))
    choices = payload.get("choices") or []
    if not choices:
        raise RuntimeError(f"empty choices in response: {payload}")
    message = choices[0].get("message") or {}
    content = message.get("content")
    if not isinstance(content, str):
        raise RuntimeError(f"missing content in response: {payload}")
    return content


JSON_BLOCK_RE = re.compile(r"```(?:json)?\s*(.*?)\s*```", re.DOTALL)


def parse_teacher_json(text: str) -> dict[str, Any]:
    text = text.strip()
    match = JSON_BLOCK_RE.search(text)
    if match:
        text = match.group(1).strip()
    try:
        parsed = json.loads(text)
    except json.JSONDecodeError:
        start = text.find("{")
        end = text.rfind("}")
        if start < 0 or end <= start:
            raise
        parsed = json.loads(text[start : end + 1])
    if not isinstance(parsed, dict):
        raise ValueError("teacher output must be a JSON object")
    return parsed


def label_one(sample: dict[str, Any], args: argparse.Namespace, api_key: str | None) -> dict[str, Any]:
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": build_user_prompt(sample, args.max_code_lines)},
    ]
    last_error = None
    raw_response = ""
    for attempt in range(args.max_retries + 1):
        try:
            raw_response = call_chat_completion(
                base_url=args.base_url,
                model=args.model,
                api_key=api_key,
                messages=messages,
                temperature=args.temperature,
                max_tokens=args.max_tokens,
                timeout=args.timeout,
            )
            parsed = parse_teacher_json(raw_response)
            out = dict(sample)
            out["teacher_model"] = args.model
            out["teacher_output"] = parsed
            out["raw_response"] = raw_response
            out["teacher_error"] = None
            return out
        except (urllib.error.URLError, TimeoutError, json.JSONDecodeError, ValueError, RuntimeError) as exc:
            last_error = str(exc)
            if attempt < args.max_retries:
                time.sleep(args.retry_sleep * (attempt + 1))
    out = dict(sample)
    out["teacher_model"] = args.model
    out["teacher_output"] = None
    out["raw_response"] = raw_response
    out["teacher_error"] = last_error
    return out


def load_completed_ids(output: Path) -> set[str]:
    if not output.exists():
        return set()
    done = set()
    for row in read_jsonl(output):
        sample_id = row.get("sample_id")
        if sample_id:
            done.add(str(sample_id))
    return done


def append_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            f.flush()


def main() -> None:
    parser = argparse.ArgumentParser(description="Label repair candidate regions with an OpenAI-compatible teacher model.")
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--base-url", required=True)
    parser.add_argument("--model", required=True)
    parser.add_argument("--api-key-env", default="OPENAI_API_KEY")
    parser.add_argument("--temperature", type=float, default=0.0)
    parser.add_argument("--max-tokens", type=int, default=2048)
    parser.add_argument("--num-workers", type=int, default=4)
    parser.add_argument("--timeout", type=int, default=180)
    parser.add_argument("--max-retries", type=int, default=2)
    parser.add_argument("--retry-sleep", type=float, default=2.0)
    parser.add_argument("--max-code-lines", type=int, default=1200)
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--no-resume", action="store_true")
    parser.add_argument("--progress-every", type=int, default=5)
    args = parser.parse_args()

    api_key = os.environ.get(args.api_key_env) or os.environ.get("QWEN_API_KEY")
    completed = set() if args.no_resume else load_completed_ids(args.output)
    samples = []
    for row in read_jsonl(args.input):
        sample_id = str(row.get("sample_id") or "")
        if sample_id and sample_id in completed:
            continue
        samples.append(row)
        if args.limit and len(samples) >= args.limit:
            break

    print(
        json.dumps(
            {
                "stage": "teacher_label_start",
                "input": str(args.input),
                "output": str(args.output),
                "base_url": args.base_url,
                "model": args.model,
                "num_workers": args.num_workers,
                "todo": len(samples),
                "resume_skipped": len(completed),
            },
            indent=2,
        ),
        flush=True,
    )
    if not samples:
        return

    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, args.num_workers)) as executor:
        futures = [executor.submit(label_one, sample, args, api_key) for sample in samples]
        buffer = []
        for idx, future in enumerate(concurrent.futures.as_completed(futures), 1):
            buffer.append(future.result())
            if len(buffer) >= 10:
                append_jsonl(args.output, buffer)
                buffer.clear()
            if args.progress_every > 0 and (idx % args.progress_every == 0 or idx == len(futures)):
                errors = sum(1 for item in buffer if item.get("teacher_error"))
                print(
                    json.dumps(
                        {
                            "stage": "teacher_label_progress",
                            "labeled": idx,
                            "total": len(futures),
                            "buffer_errors": errors,
                        }
                    ),
                    flush=True,
                )
        if buffer:
            append_jsonl(args.output, buffer)
    print(
        json.dumps(
            {
                "stage": "teacher_label_done",
                "output": str(args.output),
                "total": len(futures),
            }
        ),
        flush=True,
    )


if __name__ == "__main__":
    main()
